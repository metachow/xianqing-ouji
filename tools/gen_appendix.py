"""Write pages/appendix_<ce>.tex for every volume: 編輯說明, 異體字統一表 and 校記
(horizontal, modern setting).

usage: gen_appendix.py
Sources: text/appendix_intro.tex (hand-written), text/variants.tsv with counts taken
from the volume's transcription (the table is left out when the volume has none),
text/jiaoji.yaml (one note per entry, cited by 版心 section, leaf and side, and column;
each volume lists its own entries, numbered globally because pages link back by number).
"""
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import gen_pages  # noqa: E402

NUM = '一二三四五六七八九'


def cn(n):
    if n <= 10:
        return '十' if n == 10 else NUM[n - 1]
    t, u = divmod(n, 10)
    return ('' if t == 1 else NUM[t - 1]) + '十' + (NUM[u - 1] if u else '')


def all_chars(cfg, keys):
    """Every transcribed character on the given pages (text, notes, placed text, 眉批)."""
    for key in keys:
        info = cfg['pages'][key]
        path = gen_pages.text_path(key, info)
        if info['layout'] in ('cover', 'coverin', 'title', 'blank') or not path.exists():
            continue
        if info.get('text', 'v1') != 'v1':   # 卷二 on: pre-filled from Wikisource in standard
            continue                         # characters, no glyph forms of the original to count
        page = gen_pages.parse_page(path)
        for _, items in page.columns:
            for it in items:
                if it[0] == 'c':
                    yield it[1]
                elif it[0] == 'n':
                    yield from (c[1] for half in it[1:] for c in half if c[0] == 'c')
        for _, _, cells in page.placed:
            yield from (c[1] for c in cells if c[0] == 'c')
        for _, parts in page.notes:
            yield from (c[1] for part in parts for c in part if c[0] == 'c')


def load_jiaoji():
    """校記 entries in order; entry k is link target jj-k (gen_pages links back to it)."""
    return yaml.safe_load((ROOT / 'text' / 'jiaoji.yaml').read_text(encoding='utf-8'))


def appendix(cfg, keys, variants, jiaoji):
    """Back matter of one volume -> (tex, number of variants, number of notes)."""
    counts = Counter(ch for ch in all_chars(cfg, keys) if ch in variants)
    out = ['% generated by tools/gen_appendix.py -- do not edit\n',
           '\\begin{appendixpages}\n',
           '\\input{text/appendix_intro}\n']
    rows = sorted(counts.items(), key=lambda kv: -kv[1])
    if not rows:                       # the 編輯說明 then refers to vol. 1's table in words
        out.insert(1, '\\def\\novartable{}\n')
    if rows:
        out += ['\\clearpage\\apxsection{apx-variants}{異體字統一表}\n',
                '原刻字形在前，本版所用通行字在後，次數為本冊出現次數（含眉批）。\n\n',
                '\\begin{vartable}\n']
        per = -(-len(rows) // 3)           # three groups side by side, read down each group
        groups = [rows[i * per:(i + 1) * per] for i in range(3)]
        for i in range(per):
            cells = []
            for g in groups:
                cells.append(f'\\orig{{{g[i][0]}}}&→&{variants[g[i][0]]}&{g[i][1]}' if i < len(g) else '&&&')
            out.append('&'.join(cells) + '\\\\\n')
        out.append('\\end{vartable}\n')
    keyset = set(keys)
    mine = [(k, e) for k, e in jiaoji if e['scan'] in keyset]
    if mine:
        out += ['\\clearpage\\apxsection{apx-jiaoji}{校記}\n',
                '出處標原刻版心卷次、葉次及前後半葉（上、下），行自右數；點擊出處可轉至該頁，'
                '正文中點擊該行亦可轉回本條。\n\n',
                '\\begin{jiaoji}\n']
        for k, e in mine:
            info = cfg['pages'][e['scan']]
            half = '上' if info['side'] == 'a' else '下'
            if info['layout'] == 'title':
                where = f'扉葉牌記\\ 第{cn(e["col"])}行'
            else:
                where = f'{info["juan"]}第{info["leaf"]}葉{half}\\ 第{cn(e["col"])}行'   # 卷三十二下 would read as 卷三十二
            out.append(f'\\item[\\apxref{{scan-{e["scan"]}}}{{{where}}}]'
                       f'\\hypertarget{{jj-{k}}}{{}}{e["note"]}\n')
        out.append('\\end{jiaoji}\n')
    out.append('\\end{appendixpages}\n')
    return ''.join(out), len(rows), len(mine)


def main():
    cfg = yaml.safe_load((ROOT / 'text' / 'layout.yaml').read_text(encoding='utf-8'))
    variants = gen_pages.load_variants()
    jiaoji = list(enumerate(load_jiaoji(), 1))     # numbering is global: page back-links use it
    for vol, keys in gen_pages.volumes(cfg):
        tex, nv, nj = appendix(cfg, keys, variants, jiaoji)
        (ROOT / 'pages' / f'appendix_{vol["ce"]}.tex').write_text(tex, encoding='utf-8')
        print(f'冊{vol["slip"]}: {nv} variants, {nj} collation notes')


if __name__ == '__main__':
    main()

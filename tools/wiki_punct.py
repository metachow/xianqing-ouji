"""句讀 for 卷一 from the punctuated Wikisource text, as a separate mark layer.

usage: wiki_punct.py

The Wikisource 閑情偶寄 (詞曲部 結構第一, 詞采第二) is punctuated in modern style and
was converted from simplified characters (some characters differ). It is aligned to
the transcription of scans 036-094 character by character (difflib, after mapping
variants and dropping punctuation). A character followed by 。？！；(or ．) gets a 句
mark (small circle), one followed by ，、： a 讀 mark (tick).

Writes text/marks_wikisource.tsv (scan, column, item, mark); gen_pages.py draws it on
pages whose layout says `marks: wikisource`, instead of the marks in text/v1.
"""
import difflib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import gen_pages  # noqa: E402

JU, DOU = '。？！；．', '，、：'
SCANS = range(36, 95)
OUT = ROOT / 'text' / 'marks_wikisource.tsv'


def wiki_text():
    """Characters of the Wikisource text and, for each, the mark after it (or None)."""
    out = []
    for name in ['詞曲部_結構第一.wiki', '詞曲部_詞采第二.wiki']:
        t = (ROOT / 'text' / 'wikisource' / name).read_text(encoding='utf-8')
        t = re.sub(r'\{\{.*?\}\}', '', t, flags=re.S)
        t = re.sub(r"'''|\[\[|\]\]|<[^>]+>|◎", '', t)
        out.append(t)
    chars, marks = [], []
    for ch in ''.join(out):
        if ch in JU + DOU:
            if chars:      # a 句 mark wins over a 讀 mark at the same place
                marks[-1] = 'circle' if (ch in JU or marks[-1] == 'circle') else 'tick'
        elif '一' <= ch <= '鿿':
            chars.append(ch)
            marks.append(None)
    return chars, marks


def main():
    variants = gen_pages.load_variants()
    wchars, wmarks = wiki_text()
    cells = []                          # (scan, column, item, char) in reading order
    for s in SCANS:
        page = gen_pages.parse_page(ROOT / 'text' / 'v1' / f'{s:03d}.txt')
        for c, (_, items) in enumerate(page.columns):
            for k, it in enumerate(items):
                if it[0] == 'c':
                    cells.append((f'{s:03d}', c + 1, k + 1, it[1]))
    norm = [variants.get(c[3], c[3]) for c in cells]
    sm = difflib.SequenceMatcher(None, norm, wchars, autojunk=False)
    rows, aligned = [], 0
    for blk in sm.get_matching_blocks():
        aligned += blk.size
        for j in range(blk.size):
            mk = wmarks[blk.b + j]
            if mk:
                scan, col, item, ch = cells[blk.a + j]
                rows.append(f'{scan}\t{col}\t{item}\t{ch}\t{mk}\n')
    OUT.write_text('# scan\tcolumn\titem\tchar\tmark   (generated by tools/wiki_punct.py)\n'
                   + ''.join(rows), encoding='utf-8')
    print(f'{len(cells)} characters, {aligned} aligned ({aligned / len(cells):.0%}); '
          f'{len(rows)} marks -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()

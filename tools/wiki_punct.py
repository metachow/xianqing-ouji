"""句讀 from the punctuated Wikisource text, as a separate mark layer.

usage: wiki_punct.py               (all parts below)
       wiki_punct.py PART ...      (e.g. juan01 juan02)

The Wikisource 閑情偶寄 is punctuated in modern style and was converted from simplified
characters (some characters differ). For each part, its Wikisource sections are aligned
to the transcription of its pages character by character (difflib, after mapping
variants and dropping punctuation). A character followed by 。？！；(or ．) gets a 句
mark (small circle), one followed by ，、： a 讀 mark (tick).

Writes text/marks_wikisource.tsv (page key, column, item, char, mark), replacing the
rows of the parts processed and keeping the others; gen_pages.py draws it on pages whose
layout says `marks: wikisource`, instead of the marks in the transcription.
"""
import difflib
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / 'tools'))
import gen_pages  # noqa: E402

JU, DOU = '。？！；．', '，、：'
PARTS = {   # part: (page range in layout.yaml, Wikisource sections)
    'juan01': ('036-094', ['詞曲部_結構第一', '詞曲部_詞采第二']),
    'juan02': ('h053L-h077L', ['詞曲部_音律第三']),
    'juan03': ('h082L-h109R', ['詞曲部_賓白第四', '詞曲部_科諢第五', '詞曲部_格局第六']),
}
OUT = ROOT / 'text' / 'marks_wikisource.tsv'


def wiki_text(sections):
    """Characters of the Wikisource text and, for each, the mark after it (or None)."""
    out = []
    for name in sections:
        t = (ROOT / 'text' / 'wikisource' / f'{name}.wiki').read_text(encoding='utf-8')
        t = re.sub(r'\{\{.*?\}\}', '', t, flags=re.S)
        t = re.sub(r"'''|\[\[|\]\]|<[^>]+>|◎", '', t)
        out.append(t)
    chars, marks = [], []
    for ch in ''.join(out):
        if ch in JU + DOU:
            if chars:      # a 句 mark wins over a 讀 mark at the same place
                marks[-1] = 'circle' if (ch in JU or marks[-1] == 'circle') else 'tick'
        elif '一' <= ch <= '鿿':
            chars.append(ch)
            marks.append(None)
    return chars, marks


def part_rows(cfg, pages, sections, variants):
    wchars, wmarks = wiki_text(sections)
    cells = []                          # (page, column, item, char) in reading order
    for key in gen_pages.page_range(pages, cfg):
        page = gen_pages.parse_page(gen_pages.text_path(key, cfg['pages'][key]))
        for c, (_, items) in enumerate(page.columns):
            for k, it in enumerate(items):
                if it[0] == 'c':
                    cells.append((key, c + 1, k + 1, it[1]))
    norm = [variants.get(c[3], c[3]) for c in cells]
    sm = difflib.SequenceMatcher(None, norm, wchars, autojunk=False)
    rows, aligned = [], 0
    for blk in sm.get_matching_blocks():
        aligned += blk.size
        for j in range(blk.size):
            mk = wmarks[blk.b + j]
            if mk:
                key, col, item, ch = cells[blk.a + j]
                rows.append((key, f'{key}\t{col}\t{item}\t{ch}\t{mk}\n'))
    return rows, len(cells), aligned


def main():
    cfg = yaml.safe_load((ROOT / 'text' / 'layout.yaml').read_text(encoding='utf-8'))
    variants = gen_pages.load_variants()
    parts = sys.argv[1:] or list(PARTS)
    keep = []
    if OUT.exists():
        done = {k for p in parts for k in gen_pages.page_range(PARTS[p][0], cfg)}
        keep = [ln + '\n' for ln in OUT.read_text(encoding='utf-8').splitlines()
                if ln and not ln.startswith('#') and ln.split('\t')[0] not in done]
    new = []
    for p in parts:
        rows, n, aligned = part_rows(cfg, *PARTS[p], variants)
        new += [r for _, r in rows]
        print(f'{p}: {n} characters, {aligned} aligned ({aligned / max(1, n):.0%}); {len(rows)} marks')
    order = {k: i for i, k in enumerate(cfg['pages'])}
    body = sorted(keep + new, key=lambda r: (order.get(r.split('\t')[0], 1e9),
                                            int(r.split('\t')[1]), int(r.split('\t')[2])))
    OUT.write_text('# page\tcolumn\titem\tchar\tmark   (generated by tools/wiki_punct.py)\n' + ''.join(body),
                   encoding='utf-8')
    print(f'{len(body)} marks -> {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
